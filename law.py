def certain(text, lang="ru"):
    """Что видно без модели: требование прямое, оценивать нечего.

    Считается на каждое нажатие клавиши, поэтому только поиск по словам.
    """
    out = []
    for item in LAWS:
        if not item["certain"]:
            continue
        mark = item["insert"].strip(" ()")
        if mark and mark in text:
            continue                     # пометка уже стоит
        done = item.get("complete")
        for rx in item["rx"]:
            for m in rx.finditer(text):
                if done and re.match(done, text[m.end():]):
                    continue             # указание уже названо целиком
                if INSERTED.match(text[m.end():]):
                    continue             # пометка рядом уже стоит
                out.append({"start": m.start(), "end": m.end(),
                            "risk": item["risk"], "law": item["id"], "sign": "",
                            "why": item["certain"][lang],
                            "safe": m.group(0) + item["insert"]})
    return out


