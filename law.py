# ── подмена букв
#
# «мeфeдрон» с латинскими e и «пpивет» с латинской p выглядят как обычные
# слова, но ни одна приманка их не находит. Поэтому перед сравнением слово, в
# котором смешаны две азбуки, приводится к той, которой в нём больше. Замена
# строго побуквенная: длина строки не меняется, и все найденные места
# указывают на то же самое в исходном тексте.
LOOK = {"a": "а", "A": "А", "B": "В", "c": "с", "C": "С", "e": "е", "E": "Е",
        "H": "Н", "k": "к", "K": "К", "m": "м", "M": "М", "o": "о", "O": "О",
        "p": "р", "P": "Р", "t": "т", "T": "Т", "x": "х", "X": "Х",
        "y": "у", "Y": "У", "i": "і", "I": "І", "s": "ѕ", "S": "Ѕ",
        # Греческие буквы в ход идут реже, но идут.
        "\u03bf": "о", "\u03b1": "а", "\u03b5": "е", "\u03c1": "р",
        "\u03c7": "х", "\u03bd": "ν", "\u0391": "А", "\u0392": "В",
        "\u0395": "Е", "\u039a": "К", "\u039c": "М", "\u039d": "Н",
        "\u039f": "О", "\u03a1": "Р", "\u03a4": "Т", "\u03a7": "Х"}
BACK = {v: k for k, v in LOOK.items() if k.isascii()}
WORD_RX = re.compile(r"\w+")


def _cyrillic(ch):
    return "\u0400" <= ch <= "\u04ff"


def unmix(text):
    """Текст, в котором смешанные слова приведены к одной азбуке.

    Длина и положение символов сохраняются: по этому тексту ищутся приманки и
    имена из реестров, а показывается всё равно исходный.
    """
    out = None
    for m in WORD_RX.finditer(text):
        word = m.group()
        cyr = sum(1 for c in word if _cyrillic(c))
        lat = sum(1 for c in word if c.isascii() and c.isalpha())
        greek = sum(1 for c in word if c in LOOK and not c.isascii())
        if not (cyr and (lat or greek)) and not (greek and lat):
            continue
        table = LOOK if cyr >= lat else BACK
        if out is None:
            out = list(text)
        for n, c in enumerate(word):
            out[m.start() + n] = table.get(c, c)
    return text if out is None else "".join(out)


